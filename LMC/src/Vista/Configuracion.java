    private void seleccionDeBotonesCuentas(JButton botonSelecionado){
        JButton[] botonesCuentas= new JButton[]{jButton3, jButton4, jButton5, jButton6};
        Color defaultBackgroundColor= new JButton().getBackground();
        Color defaultForegroundColor= new JButton().getForeground();
        for(JButton boton : botonesCuentas){
            if(boton == botonSelecionado){
                botonSelecionado.setBackground(jTable1.getSelectionBackground());
                botonSelecionado.setForeground(jTable1.getSelectionForeground());
            }
            else{
                boton.setBackground(defaultBackgroundColor);
                boton.setForeground(defaultForegroundColor);
            }
        }
    }
    
    /*mostrar ventana de credenciales para crear una nueva cuenta,
    para cambiar las credenciales de una cuenta ya creada o para crear un 
    nuevo usuario(rol) para postgreSQL*/
    private void mostrarVentanaDeCredenciales(){
        if(tema.contains("Dar") || tema.contains("HiFi") || tema.contains("Noire"))
            jLabel4.setIcon(new ImageIcon(getClass().getResource("/Iconos/eye_b.png")));
        else jLabel4.setIcon(new ImageIcon(getClass().getResource("/Iconos/eye.png")));
        //<editor-fold defaultstate="collapsed" desc="configura los campos de nombre de cuenta y contraseña">
        String nombre, password;
        if(Credenciales.getTitle().equals("Nueva Cuenta")){
            nombre= "nombre de cuenta";
            password= "contraseña";
        }
        else if(Credenciales.getTitle().equals("Nuevo Usuario")){
            nombre= "nombre de usuario o rol";
            password= "contraseña";
        }
        else {
            nombre= "nuevo nombre de cuenta";
            password= "nueva contraseña";
        }
        jTextField1.setText(nombre);
        jTextField1.setForeground(Color.GRAY);
        for(java.awt.event.FocusListener L : jTextField1.getFocusListeners())
            if(L instanceof FocusAdapter)
                jTextField1.removeFocusListener(L);
        jTextField1.addFocusListener(new FocusAdapter() {
            //<editor-fold defaultstate="collapsed" desc="lo que pasa cuando se da click en el nombre de la cuenta o fuera de él">
            @Override
            public void focusGained(FocusEvent e) {
                super.focusGained(e);
                if(jTextField1.getForeground().equals(Color.GRAY)){
                    jTextField1.setText("");
                    jTextField1.setForeground(new JTextField().getForeground());
                }
            }
            @Override
            public void focusLost(FocusEvent e) {
                super.focusLost(e);
                if(jTextField1.getText().equals("")){
                    jTextField1.setText(nombre);
                    jTextField1.setForeground(Color.GRAY);
                }
            }
            //</editor-fold>
        });
        jPasswordField1.setText(password);
        jPasswordField1.setForeground(Color.GRAY);
        jPasswordField1.setEchoChar((char)0);
        for(java.awt.event.FocusListener L : jPasswordField1.getFocusListeners())
            if(L instanceof FocusAdapter)
                jPasswordField1.removeFocusListener(L);
        jPasswordField1.addFocusListener(new FocusAdapter() {
            //<editor-fold defaultstate="collapsed" desc="lo que pasa cuando se da click en la contraseña o fuera de ella">
            @Override
            public void focusGained(FocusEvent e) {
                super.focusGained(e);
                if(jPasswordField1.getForeground().equals(Color.GRAY)){
                    jPasswordField1.setText("");
                    jPasswordField1.setForeground(new JPasswordField().getForeground());
                    jPasswordField1.setEchoChar('\u2022');
                }
            }
            @Override
            public void focusLost(FocusEvent e) {
                super.focusLost(e);
                if(String.valueOf(jPasswordField1.getPassword()).equals("")){
                    jPasswordField1.setText(password);
                    jPasswordField1.setForeground(Color.GRAY);
                    jPasswordField1.setEchoChar((char)0);
                    if(tema.contains("Dar") || tema.contains("HiFi") || tema.contains("Noire"))
                        jLabel4.setIcon(new ImageIcon(getClass().getResource("/Iconos/eye_b.png")));
                    else jLabel4.setIcon(new ImageIcon(getClass().getResource("/Iconos/eye.png")));
                }
            }
            //</editor-fold>
        });
        //</editor-fold>
        Credenciales.pack();
        Credenciales.setLocationRelativeTo(this);
        Credenciales.setVisible(true);
    }
    
    private void adminCuentas(String operacion){
        DefaultTableModel tabla= (DefaultTableModel)jTable1.getModel();
        //<editor-fold defaultstate="collapsed" desc="las operaciones de la sección cuentas">
        if(operacion.equals("asignar")){
            controladorConf.cuentasService().adminCuentas(OpcionesConfig.CuentasAdmin.GET_CUENTAS_DB, null);
            for(Object[] cuenta : controladorConf.cuentasService().getCuentas()){
                String passwordProtected= "";
                for(int i= 0; i < 10; i++)
                    passwordProtected+= '\u2022';
                Object[] rowData= new Object[]{cuenta[1], passwordProtected, cuenta[3]};
                tabla.addRow(rowData);
            }
            //esto es para el tamaño de las columnas
            jTable1.getColumnModel().getColumn(0).setPreferredWidth(jTable1.getParent().getWidth() - 290);
            jTable1.getColumnModel().getColumn(1).setPreferredWidth(200);
            jTable1.getColumnModel().getColumn(2).setPreferredWidth(90);
            //esto es para cuando se de click sobre el checkbox de la columna SuperAdmin.
            jTable1.addMouseListener(new MouseAdapter() {
                @Override
                public void mousePressed(MouseEvent e) {
                    //<editor-fold defaultstate="collapsed" desc="Código">
                    super.mousePressed(e);
                    Point coorMouse= e.getPoint();
                    for(int row= 0; row < jTable1.getRowCount(); row++){
                        int column= 0;
                        for(int col= 0; col < 3; col++)
                            if(jTable1.getColumnName(col).equals("SuperAdmin."))
                                column= col;
                        int coordX= jTable1.getCellRect(row, column, false).x + 40;
                        int coordY= jTable1.getCellRect(row, column, false).y + 5;
                        if(coorMouse.x > coordX && coorMouse.x < (coordX + 10) 
                                && coorMouse.y > coordY && coorMouse.y < (coordY + 10)){
                            boolean valor= (boolean)jTable1.getValueAt(row, column);
                            valor= !valor;
                            //con la siguiente condición se garantiza que exista al menos 1 superadministrador
                            if(!valor){
                                int cantSuper= 0;
                                for(int i= 0; i < jTable1.getRowCount(); i++)
                                    if((boolean)jTable1.getValueAt(i, column))
                                        cantSuper+= 1;
                                if(cantSuper == 1){
                                    JOptionPane.showMessageDialog(null, "Debe de existir al menos un Superadministrador",
                                            "Advertencia", JOptionPane.WARNING_MESSAGE);
                                    return;
                                }
                            }
                            //agrega el valor de superAdmin a la tabla
                            jTable1.setValueAt(valor, row, column);
                            /*actualiza el superAdmin de la cuenta en la lista 
                            de cuentas en el controlador*/
                            String AdminName= tabla.getValueAt(row, 0).toString();
                            controladorConf.cuentasService().setSuperAdmin(AdminName, valor);
                            break;
                        }
                    }
                    //</editor-fold>
                }
            });
        }
        else if(operacion.equals("añadir")){
            jButton7.setText("Añadir");
            jButton7.setIcon(new ImageIcon(getClass().getResource("/Iconos/plus.png")));
            Credenciales.setTitle("Nueva Cuenta");
            mostrarVentanaDeCredenciales();
        }
        else if(operacion.equals("eliminar")){
            int fila= jTable1.getSelectedRow();
            if(fila == -1){
                JOptionPane.showMessageDialog(this, "Debe seleccionar una cuenta a eliminar"
                        , "Eliminar cuenta", JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            Object AdminName= tabla.getValueAt(fila, 0);
            controladorConf.cuentasService().adminCuentas(OpcionesConfig.CuentasAdmin.ERASE_CUENTA,
                    new Object[]{AdminName});
            tabla.removeRow(fila);
            mostrarMSG(this, "Cuenta eliminada");
        }
        else if(operacion.equals("credenciales")){
            int fila= jTable1.getSelectedRow();
            if(fila == -1){
                JOptionPane.showMessageDialog(this, "Debe seleccionar una cuenta para cambiar sus credenciales"
                        , "Cambiar credenciales de la cuenta", JOptionPane.INFORMATION_MESSAGE);
                return;
            }
            jButton7.setText("Cambiar");
            jButton7.setIcon(new ImageIcon(getClass().getResource("/Iconos/actualización.png")));
            Credenciales.setTitle("Cambiar Credenciales");
            mostrarVentanaDeCredenciales();
        }
        else if(operacion.equals("actualizar")){
            /*aunque se creen cuentas nuevas, se modifiquen las credenciales o se eliminen cuentas existentes,
            realmente lo que se hace es realizar esas operaciones a una lista de cuentas en el controlador,
            no se realizan en la base de datos, para que los cambios tengan efecto en la BD,
            se deben aplicar los cambios con el botón "Actualizar cambios"*/
            controladorConf.cuentasService().adminCuentas(OpcionesConfig.CuentasAdmin.UPDATE_DB, null);
            /*después de actualizar la BD, oculta todas las contraseñas
            agregadas (de cuentas nuevas) o modificadas en la tabla*/
            String passwordProtected= "";
            for(int i= 0; i < 10; i++)
                passwordProtected+= '\u2022';
            for(int i= 0; i < tabla.getRowCount(); i++)
                tabla.setValueAt(passwordProtected, i, 1);
            if(controladorConf.getCambios()){
                String nombreSuperAdmin= ((Vista.Inicio)this.getOwner()).getNombreAdmin();
                gestionEventos.agregarEvento("Responsable: " + nombreSuperAdmin + "\n" + 
                        "Lugar: Sistema\n" + "El superadministrador realizó cambios en las cuentas");
                controladorConf.resetCambios();
            }
            mostrarMSG(this, "Los cambios realizados se han actualizado en la Base de datos");
        }
        //</editor-fold>
    }
    

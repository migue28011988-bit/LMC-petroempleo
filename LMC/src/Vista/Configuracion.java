    /*acción del botón "Establecer" el cual toma el usuario y la 
    contraseña de la autentificación de la base de datos y la guarda en el
    archivo de configuración lo que servirá para establecer la conexión
    a la base de datos cada vez que se necesite*/
    private void jButton18ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton18ActionPerformed
        String usuario= jTextField3.getText();
        String password= String.valueOf(jPasswordField2.getPassword());
        if(usuario.equals("") || password.equals("")){
            JOptionPane.showMessageDialog(this, "Credenciales incompletas",
                    "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        //si el usuario es el mismo que el que está guardado no hace nada
        if(usuario.equals(OpcionesConfig.LocalConfig.getCredenciales()[0]))
            return;
        
        /*se registra el evento antes de guardar las credenciales para que
        se registre en la BD actual con el usuario actual ya que si cambia
        el usuario y no es propietario de dicha BD dará error y no se
        registrará el evento*/
        String nombreSuperAdmin= ((Vista.Inicio)this.getOwner()).getNombreAdmin();
        gestionEventos.agregarEvento("Responsable: " + nombreSuperAdmin + "\n" + 
                "Lugar: Sistema\n" + "El superadministrador cambió las credenciales"+
                " para la conexión al servidor de postgreSQL");
        
        //guarda las credenciales en el archivo de configuración
        OpcionesConfig.LocalConfig.setCredenciales(new String[]{usuario, password});
        
        //oculta la contraseña
        jPasswordField2.setText("");
        
        cambioROL= true;
        
        mostrarMSG(this, "Credenciales establecidas");
    }//GEN-LAST:event_jButton18ActionPerformed


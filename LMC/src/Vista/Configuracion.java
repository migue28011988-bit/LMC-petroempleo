    /*Exporta el certificado público desde el KeyStore generado,
    el administrador puede escoger la carpeta donde se guardará y el nombre*/
    private void jButton9ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton9ActionPerformed
        //Verificar que el keystore exista
        File keystoreFile = new File("servidor.keystore");
        if (!keystoreFile.exists()) {
            JOptionPane.showMessageDialog(this, "No se encontró el archivo" + 
                    " servidor.keystore en el directorio actual.\n" + 
                    "Asegúrate de que existe antes de exportar.", "Error", 
                    JOptionPane.ERROR_MESSAGE);
            return;
        }
        int resultado= guardaCertificado.showSaveDialog(this);
        if (resultado != javax.swing.JFileChooser.APPROVE_OPTION)
            return;
        File archivoDestino= guardaCertificado.getSelectedFile();
        // Asegurar extensión .crt
        if (!archivoDestino.getName().toLowerCase().endsWith(".crt"))
            archivoDestino = new File(archivoDestino.getAbsolutePath() + ".crt");
        try{
            Loading loading= new Loading(this, ModalityType.APPLICATION_MODAL);
            String[] estado= new String[1];
            final File path= archivoDestino;
            
            loading.execMetodo(()-> estado[0]= controladorConf.SSLCertService().exportarCertificado(path));
            
            if(estado[0].equals("éxito")){
                String nombreSuperAdmin= ((Vista.Inicio)this.getOwner()).getNombreAdmin();
                gestionEventos.agregarEvento("Responsable: " + nombreSuperAdmin + "\n" + 
                        "Lugar: Sistema\n" + "El superadministrador creó un "+
                        "certificado público nuevo");
                mostrarMSG(this, "El certificado público se guardó correctamente");
            }
            else 
                JOptionPane.showMessageDialog(this, "El certificado público" + 
                        " no se pudo guardar", "Error", 
                        JOptionPane.ERROR_MESSAGE);
        }catch(RuntimeException e){
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", 
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton9ActionPerformed


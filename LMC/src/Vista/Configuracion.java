    private void asignarValoresPorDefecto(){
        //<editor-fold defaultstate="collapsed" desc="asigna los valores del archivo de configuración a la interfaz de usuario">
        
        //asigna el tiempo de espera al combobox
        Integer tiempoEspera= OpcionesConfig.LocalConfig.getTiempoEspera();
        switch(tiempoEspera){
            case 15000-> jComboBox1.setSelectedItem("15 segundos");
            case 30000-> jComboBox1.setSelectedItem("30 segundos");
            case 60000-> jComboBox1.setSelectedItem("1 minuto");
            case 600000-> jComboBox1.setSelectedItem("10 minutos");
            case 1800000-> jComboBox1.setSelectedItem("30 minutos");
            case 3600000-> jComboBox1.setSelectedItem("1 hora");
        }
        /*Cuando se cambia el valor del tiempo de espera de la actualización
        automática, este se guarda en el archivo de configuración*/
        Configuracion estaVentana= this;
        jComboBox1.addItemListener(new ItemListener() {
            @Override
            public void itemStateChanged(ItemEvent e) {
                if(e.getStateChange() == java.awt.event.ItemEvent.SELECTED){
                    String valor= jComboBox1.getSelectedItem().toString();
                    switch(valor){
                        case "15 segundos"-> OpcionesConfig.LocalConfig.setTiempoEspera(15000);
                        case "30 segundos"-> OpcionesConfig.LocalConfig.setTiempoEspera(30000);
                        case "1 minuto"-> OpcionesConfig.LocalConfig.setTiempoEspera(60000);
                        case "10 minutos"-> OpcionesConfig.LocalConfig.setTiempoEspera(600000);
                        case "30 minutos"-> OpcionesConfig.LocalConfig.setTiempoEspera(1800000);
                        case "1 hora"-> OpcionesConfig.LocalConfig.setTiempoEspera(3600000);
                    }
                    String nombreSuperAdmin= ((Vista.Inicio)estaVentana.getOwner()).getNombreAdmin();
                    gestionEventos.agregarEvento("Responsable: " + nombreSuperAdmin + "\n" + 
                            "Lugar: Sistema\n" + "El superadministrador cambió el tiempo de"+
                            " espera de la actualización automática");
                }
            }
        });
        
        /*se obtienen las exclusiones desde el archivo de configuración*/
        exclusiones= OpcionesConfig.LocalConfig.getExclusiones();
        //asigna las exclusiones a la tabla de exclusiones
        DefaultTableModel tabla= (DefaultTableModel)jTable2.getModel();
        tabla.setRowCount(0);
        for(String ip : exclusiones) 
            tabla.addRow(new Object[]{ip, ""});
        
        /*se asignan la url de la conexión a la BD a los componentes
        correspondientes en la sección conexión de la base de datos*/
        String url= OpcionesConfig.LocalConfig.getURL();
        //agrega el nombre de la BD
        jTextField2.setText(url.split("/")[3]);
        //agrega el ip del servidor de la BD
        String ip= url.split("/")[2].split(":")[0];
        if(ip.equals("localhost"))
            ip= "127.0.0.1";
        jTextField5.setText(ip);
        //agrega el puerto de conexión
        jFormattedTextField3.setValue(url.split("/")[2].split(":")[1]);
        //establece la url completa
        jLabel23.setText(url.substring(16));
        
        /*se asignan el usuario y la contraseña a la sección autentificación
        de la base de datos*/
        String[] autentif= OpcionesConfig.LocalConfig.getCredenciales();
        //agrega el usuario
        jTextField3.setText(autentif[0]);
        //carácter de la contraseña oculta
        jPasswordField2.setEchoChar('\u2022');
        if(tema.contains("Dar") || tema.contains("HiFi") || tema.contains("Noire"))
            jLabel26.setIcon(new ImageIcon(getClass().getResource("/Iconos/eye_b.png")));
        else jLabel26.setIcon(new ImageIcon(getClass().getResource("/Iconos/eye.png")));
        
        //</editor-fold>
    }
    
